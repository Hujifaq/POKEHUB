export const THEME_FIRE_PALETTES = {
  obsidian: ['transparent', '#15092a', '#380f5c', '#5f1e94', '#8a2be2', '#b388ff', '#d8b4fe', '#ffffff'],
  gold: ['transparent', '#261a00', '#593e00', '#8a6200', '#c29200', '#ffd700', '#fff4a3', '#ffffff'],
  cyber: ['transparent', '#001a24', '#004760', '#007e9e', '#00a8b5', '#00f0ff', '#ff80bf', '#ffffff'],
  emerald: ['transparent', '#041f11', '#0b4d29', '#146939', '#1e824c', '#2ecc71', '#85ffaa', '#ffffff'],
  sakura: ['transparent', '#26000f', '#590022', '#99003a', '#cc004e', '#ff2a6d', '#ffa6c9', '#ffffff'],
  retro: ['transparent', '#050508', '#0a0b10', '#12141c', '#1b1d28', '#282b3a', '#3c4155', '#161720']
}

export function PixelFireAura({ themeStyle = 'obsidian', isHovered = false }) {
  const canvasRef = useRef(null)
  const isDarkSmoke = themeStyle === 'retro' || themeStyle === 'obsidian_dark'

  useEffect(() => {
    const canvas = canvasRef.current
    if (!canvas) return
    const ctx = canvas.getContext('2d')
    if (!ctx) return

    const W = 36
    const H = 48
    canvas.width = W
    canvas.height = H

    const palette = THEME_FIRE_PALETTES[themeStyle] || THEME_FIRE_PALETTES.obsidian
    const fireBuffer = new Uint8Array(W * H)
    let animationFrameId
    let lastTime = 0
    let tick = 0
    const fps = isDarkSmoke ? 20 : 24
    const interval = 1000 / fps

    // Flush tightly hugging the card perimeter
    const cardLeft = 2
    const cardRight = W - 2
    const cardTop = 6
    const cardBottom = H - 2

    const embers = Array.from({ length: isDarkSmoke ? 16 : 14 }, () => ({
      x: cardLeft + Math.random() * (cardRight - cardLeft),
      y: cardBottom - Math.random() * (H * 0.7),
      vy: isDarkSmoke ? 0.25 + Math.random() * 0.4 : 0.35 + Math.random() * 0.6,
      vx: (Math.random() - 0.5) * 0.3,
      size: isDarkSmoke ? Math.floor(Math.random() * 2) + 1 : 1,
      life: Math.random() * 20 + 10,
      maxLife: 30
    }))

    const render = (time) => {
      animationFrameId = requestAnimationFrame(render)
      if (time - lastTime < interval) return
      lastTime = time
      tick++

      const intensityMultiplier = isHovered ? 1.4 : 1.1

      // 1. Bottom edge flame injection (flames hug bottom rim)
      for (let x = cardLeft; x <= cardRight; x++) {
        const baseHeat = Math.random() > 0.08 ? Math.floor((Math.random() * 3 + 5) * intensityMultiplier) : 0
        fireBuffer[(cardBottom - 1) * W + x] = Math.min(palette.length - 1, baseHeat)
        fireBuffer[cardBottom * W + x] = Math.min(palette.length - 1, baseHeat)
      }

      // 2. Top edge flame injection (flames crowning the top rim)
      for (let x = cardLeft; x <= cardRight; x++) {
        if (Math.random() > 0.15) {
          const topHeat = Math.floor((Math.random() * 3 + 4) * intensityMultiplier)
          fireBuffer[cardTop * W + x] = Math.min(palette.length - 1, topHeat)
          fireBuffer[(cardTop + 1) * W + x] = Math.min(palette.length - 1, topHeat)
        }
      }

      // 3. Left & right edge flames (flames tightly wrapping left & right sides)
      for (let y = cardTop; y <= cardBottom; y++) {
        if (Math.random() > 0.2) {
          const sideHeat = Math.floor((Math.random() * 3 + 4) * intensityMultiplier)
          fireBuffer[y * W + cardLeft] = Math.min(palette.length - 1, sideHeat)
          fireBuffer[y * W + cardRight] = Math.min(palette.length - 1, sideHeat)
        }
      }

      // Propagate heat upwards (rising flame tongues)
      for (let y = 1; y < H; y++) {
        for (let x = 0; x < W; x++) {
          const srcIdx = y * W + x
          const pixel = fireBuffer[srcIdx]
          if (pixel === 0) {
            fireBuffer[(y - 1) * W + x] = 0
          } else {
            const decay = Math.random() < 0.25 ? 0 : 1
            const spread = Math.floor(Math.random() * 3) - 1
            const dstX = Math.max(0, Math.min(W - 1, x + spread))
            const dstY = y - 1
            const newPixel = pixel > decay ? pixel - decay : 0
            fireBuffer[dstY * W + dstX] = newPixel
          }
        }
      }

      // Clear canvas & draw pixel fire
      ctx.clearRect(0, 0, W, H)

      for (let y = 0; y < H; y++) {
        for (let x = 0; x < W; x++) {
          const val = fireBuffer[y * W + x]
          if (val > 0) {
            ctx.fillStyle = palette[val] || palette[palette.length - 1]
            ctx.fillRect(x, y, 1, 1)
          }
        }
      }

      // Draw floating embers closely attached to card perimeter
      for (let i = 0; i < embers.length; i++) {
        const e = embers[i]
        e.y -= e.vy * intensityMultiplier
        e.x += e.vx
        e.life--

        if (e.y < 2 || e.life <= 0 || e.x < cardLeft - 1 || e.x > cardRight + 1) {
          e.x = cardLeft + Math.random() * (cardRight - cardLeft)
          e.y = cardBottom - Math.random() * 2
          e.life = Math.random() * 20 + 10
          e.vy = isDarkSmoke ? 0.25 + Math.random() * 0.4 : 0.35 + Math.random() * 0.6
        }

        const smokeLevel = Math.min(palette.length - 1, Math.floor((e.life / e.maxLife) * 5) + 2)
        ctx.fillStyle = palette[smokeLevel] || palette[palette.length - 1]
        const pSize = isDarkSmoke ? (e.size || 1) : 1
        ctx.fillRect(Math.floor(e.x), Math.floor(e.y), pSize, pSize)
      }
    }

    animationFrameId = requestAnimationFrame(render)

    return () => {
      cancelAnimationFrame(animationFrameId)
    }
  }, [themeStyle, isHovered, isDarkSmoke])

  return (
    <div className="absolute -top-2.5 -bottom-0.5 -left-1 -right-1 sm:-top-3 sm:-bottom-1 sm:-left-1.5 sm:-right-1.5 pointer-events-none z-0 flex items-center justify-center overflow-visible select-none [transform:translateZ(-1px)]">
      <canvas
        ref={canvasRef}
        className="w-full h-full object-fill opacity-95 filter drop-shadow-[0_0_8px_rgba(0,0,0,0.85)]"
        style={{
          imageRendering: 'pixelated'
        }}
      />
    </div>
  )
}

